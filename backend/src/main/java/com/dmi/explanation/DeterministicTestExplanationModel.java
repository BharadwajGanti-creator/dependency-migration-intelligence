package com.dmi.explanation;

import com.dmi.domain.ExplanationClaim;
import com.dmi.domain.StructuredExplanation;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Component;

import java.util.List;
import java.util.Optional;

/**
 * Test-only adapter: synthesizes schema-valid explanations from pack facts without external inference.
 * Enabled only when {@code dmi.explanation.provider=deterministic-test}.
 */
@Component
@ConditionalOnProperty(name = "dmi.explanation.provider", havingValue = "deterministic-test")
public class DeterministicTestExplanationModel implements ExplanationModel {

    private long lastLatencyMs;

    @Override
    public boolean isAvailable() {
        return true;
    }

    @Override
    public StructuredExplanation generate(EvidencePack pack) {
        long start = System.nanoTime();
        String verdictItem = pack.items().stream()
                .filter(i -> i.kind() == EvidenceKind.REVIEWED_VERDICT && "Reviewed verdict".equals(i.label()))
                .map(EvidenceItem::detail)
                .findFirst()
                .orElse("UNVERIFIED");

        String summary = "Deterministic test explanation for " + pack.findingId()
                + " aligned with reviewed verdict " + verdictItem + ".";
        List<ExplanationClaim> claims = List.of(new ExplanationClaim(
                "Reviewed migration consequence remains " + verdictItem + " for this evidence pack.",
                List.of(firstEvidenceId(pack, EvidenceKind.REVIEWED_VERDICT))));

        lastLatencyMs = (System.nanoTime() - start) / 1_000_000;
        return new StructuredExplanation(
                pack.findingId(),
                summary,
                claims,
                List.of("Re-run offline OpenRewrite dryRun on an isolated fixture copy."),
                List.of("Generated by deterministic-test provider; not real model inference."));
    }

    private static String firstEvidenceId(EvidencePack pack, EvidenceKind kind) {
        return pack.items().stream()
                .filter(i -> i.kind() == kind)
                .map(EvidenceItem::id)
                .findFirst()
                .orElse("ev-1");
    }

    @Override
    public Optional<Long> lastLatencyMs() {
        return Optional.of(lastLatencyMs);
    }
}
